import fs from 'fs';
import https from 'https';

const agent = new https.Agent({ rejectUnauthorized: false });
const headers = {
  'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
  'Accept': 'application/json, text/plain, */*'
};

async function fetchMediaForPost(postId) {
  try {
    const res = await fetch(`https://bankseizedcars.online/wp-json/wp/v2/media?parent=${postId}`, { agent, headers });
    if (!res.ok) return [];
    const data = await res.json();
    return data.map(m => m.source_url).filter(Boolean);
  } catch (err) {
    console.error(`Error fetching media for post ${postId}:`, err.message);
    return [];
  }
}

async function fetchAllProducts() {
  let allProducts = [];
  let page = 1;
  const perPage = 40;

  console.log("Starting full inventory extraction from bankseizedcars.online...");

  while (true) {
    try {
      console.log(`Fetching page ${page}...`);
      const res = await fetch(`https://bankseizedcars.online/wp-json/wp/v2/product?per_page=${perPage}&page=${page}&_embed=1`, { agent, headers });
      
      if (!res.ok) {
        if (res.status === 400) break;
        throw new Error(`HTTP ${res.status}`);
      }

      const data = await res.json();
      if (data.length === 0) break;
      
      allProducts.push(...data);
      console.log(`Successfully fetched ${data.length} products from page ${page}.`);
      page++;
    } catch (err) {
      console.error(`Error fetching page ${page}:`, err.message);
      break; 
    }
  }

  return allProducts;
}

// Helper to batch process promises
async function processInBatches(items, batchSize, processFn) {
  let results = [];
  for (let i = 0; i < items.length; i += batchSize) {
    const batch = items.slice(i, i + batchSize);
    const batchResults = await Promise.all(batch.map(processFn));
    results.push(...batchResults);
    process.stdout.write(`\rProcessed ${Math.min(i + batchSize, items.length)} / ${items.length} posts for media...`);
  }
  console.log(); // Newline after progress
  return results;
}

function parsePrice(text) {
  if (!text) return 0;
  // Look for "Price: $14k", "Price: $13,999", "Price: $2,500"
  const match = text.match(/Price:\s*\$?([\d,]+)[kK]?/i);
  if (match) {
    let numStr = match[1].replace(/,/g, '');
    let num = parseFloat(numStr);
    if (text.match(/Price:\s*\$?[\d,]+[kK]/i)) {
      num = num * 1000;
    }
    return num;
  }
  return 0; // Default if not found
}

async function run() {
  const products = await fetchAllProducts();
  
  if (products.length === 0) {
    console.error("No products could be fetched. Please ensure the server is online and not blocking requests.");
    return;
  }

  console.log(`\nTotal products extracted: ${products.length}`);
  console.log(`Fetching gallery images for all ${products.length} products (this may take a minute)...`);

  // Fetch all media in batches of 10 to avoid overwhelming the server
  const mediaResults = await processInBatches(products, 10, async (p) => {
    return await fetchMediaForPost(p.id);
  });

  let sql = `-- Seed file generated by full inventory scraper\n`;
  sql += `-- Instructions: Copy and paste this into your Supabase SQL Editor to insert vehicles.\n\n`;

  products.forEach((p, index) => {
    const featuredMedia = p._embedded?.['wp:featuredmedia']?.[0]?.source_url;
    const galleryImages = mediaResults[index] || [];
    
    let allImages = [];
    if (featuredMedia) allImages.push(featuredMedia);
    allImages.push(...galleryImages);
    allImages = [...new Set(allImages)]; // Remove duplicates
    
    const imagesSql = allImages.length > 0 
      ? `ARRAY[${allImages.map(img => `'${img.replace(/'/g, "''")}'`).join(', ')}]::text[]`
      : `ARRAY[]::text[]`;

    const terms = p._embedded?.['wp:term']?.[0] || [];
    const category = terms.length > 0 ? terms[0].name.replace(/'/g, "''") : 'Unknown';
    
    const title = p.title.rendered.replace(/&#(\d+);/g, (m, dec) => String.fromCharCode(dec)).replace(/&amp;/g, '&');
    const name = title.replace(/'/g, "''");
    const slug = p.slug.replace(/'/g, "''");
    
    // Parse Year and Make from Title
    let year = 2024;
    let make = "Unknown";
    const yearMatch = title.match(/^(20\d{2}|19\d{2})/);
    if (yearMatch) {
        year = parseInt(yearMatch[1]);
        const rest = title.replace(yearMatch[1], '').trim();
        if (rest.toLowerCase().includes("ferrari")) make = "Ferrari";
        else if (rest.toLowerCase().includes("bmw")) make = "BMW";
        else if (rest.toLowerCase().includes("mercedes")) make = "Mercedes-Benz";
        else if (rest.toLowerCase().includes("audi")) make = "Audi";
        else if (rest.toLowerCase().includes("ford")) make = "Ford";
        else if (rest.toLowerCase().includes("toyota")) make = "Toyota";
        else if (rest.toLowerCase().includes("rollsroyce") || rest.toLowerCase().includes("rolls royce")) make = "Rolls-Royce";
        else if (rest.toLowerCase().includes("lamborghini")) make = "Lamborghini";
        else if (rest.toLowerCase().includes("maserati")) make = "Maserati";
        else if (rest.toLowerCase().includes("porsche")) make = "Porsche";
        else if (rest.toLowerCase().includes("chevrolet")) make = "Chevrolet";
        else if (rest.toLowerCase().includes("dodge")) make = "Dodge";
        else if (rest.toLowerCase().includes("lexus")) make = "Lexus";
        else make = rest.substring(0, 20); 
    }

    const rawDesc = p.content.rendered.replace(/(<([^>]+)>)/gi, "").trim();
    const desc = rawDesc.replace(/'/g, "''").substring(0, 1500);
    
    // Parse Price from description
    const price = parsePrice(rawDesc);

    sql += `INSERT INTO public.vehicles (slug, name, description, price, make, year, body_type, images, is_sold, created_at)\n`;
    sql += `VALUES (\n`;
    sql += `  '${slug}',\n`;
    sql += `  '${name}',\n`;
    sql += `  '${desc}',\n`;
    sql += `  ${price},\n`;
    sql += `  '${make}',\n`;
    sql += `  ${year},\n`;
    sql += `  '${category}',\n`;
    sql += `  ${imagesSql},\n`;
    sql += `  false,\n`;
    sql += `  '${p.date}'\n`;
    sql += `) ON CONFLICT (slug) DO UPDATE SET \n`;
    sql += `  name = EXCLUDED.name,\n`;
    sql += `  description = EXCLUDED.description,\n`;
    sql += `  price = EXCLUDED.price,\n`;
    sql += `  make = EXCLUDED.make,\n`;
    sql += `  year = EXCLUDED.year,\n`;
    sql += `  body_type = EXCLUDED.body_type,\n`;
    sql += `  images = EXCLUDED.images,\n`;
    sql += `  is_sold = EXCLUDED.is_sold,\n`;
    sql += `  created_at = EXCLUDED.created_at;\n\n`;
  });

  const outputPath = 'supabase/migrations/seed_all_vehicles.sql';
  fs.writeFileSync(outputPath, sql, 'utf8');
  console.log(`\nSuccess! Fully aligned SQL seed file generated at: ${outputPath}`);
}

run();
