import fs from 'fs';
import https from 'https';

const agent = new https.Agent({ rejectUnauthorized: false });
const headers = {
  'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36',
  'Accept': 'application/json'
};

async function fetch40Products() {
  console.log("Fetching 40 products from the WooCommerce Store API...");
  try {
    const res = await fetch('https://bankseizedcars.online/wp-json/wc/store/products?per_page=40', { agent, headers });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json();
    return data;
  } catch (err) {
    console.error(`Error fetching products:`, err.message);
    return [];
  }
}

async function run() {
  const products = await fetch40Products();
  
  if (products.length === 0) {
    console.error("No products could be fetched.");
    return;
  }

  console.log(`Successfully fetched exactly ${products.length} products with all prices and images!`);

  let sql = `-- Seed file generated by WC Store API scraper\n`;
  sql += `-- Instructions: Copy and paste this into your Supabase SQL Editor to insert vehicles.\n\n`;

  products.forEach((p) => {
    // 1. Extract Images directly from WooCommerce response
    const allImages = p.images.map(img => img.src);
    const imagesSql = allImages.length > 0 
      ? `ARRAY[${allImages.map(img => `'${img.replace(/'/g, "''")}'`).join(', ')}]::text[]`
      : `ARRAY[]::text[]`;

    // 2. Extract Category
    const category = p.categories && p.categories.length > 0 ? p.categories[0].name.replace(/'/g, "''") : 'Unknown';
    
    // 3. Clean Title and Slug
    const title = p.name.replace(/&#(\d+);/g, (m, dec) => String.fromCharCode(dec)).replace(/&amp;/g, '&');
    const name = title.replace(/'/g, "''");
    
    // Ensure slug doesn't have weird characters if title is funky
    let slug = p.slug || name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)+/g, '');
    slug = slug.replace(/'/g, "''");

    // 4. Extract Price
    // WC Store API returns price in minor units (e.g., 3000000 for $30,000.00)
    let price = 0;
    if (p.prices && p.prices.price) {
       const minorUnit = p.prices.currency_minor_unit || 2;
       price = parseInt(p.prices.price, 10) / Math.pow(10, minorUnit);
    }
    
    // 5. Parse Year and Make from Title
    let year = 2024;
    let make = "Unknown";
    const yearMatch = title.match(/^(20\d{2}|19\d{2})/);
    if (yearMatch) {
        year = parseInt(yearMatch[1]);
        const rest = title.replace(yearMatch[1], '').trim();
        const restLower = rest.toLowerCase();
        if (restLower.includes("ferrari")) make = "Ferrari";
        else if (restLower.includes("bmw")) make = "BMW";
        else if (restLower.includes("mercedes")) make = "Mercedes-Benz";
        else if (restLower.includes("audi")) make = "Audi";
        else if (restLower.includes("ford")) make = "Ford";
        else if (restLower.includes("toyota")) make = "Toyota";
        else if (restLower.includes("rollsroyce") || restLower.includes("rolls royce")) make = "Rolls-Royce";
        else if (restLower.includes("lamborghini")) make = "Lamborghini";
        else if (restLower.includes("maserati")) make = "Maserati";
        else if (restLower.includes("porsche")) make = "Porsche";
        else if (restLower.includes("chevrolet")) make = "Chevrolet";
        else if (restLower.includes("dodge")) make = "Dodge";
        else if (restLower.includes("lexus")) make = "Lexus";
        else if (restLower.includes("kia")) make = "Kia";
        else if (restLower.includes("gmc")) make = "GMC";
        else if (restLower.includes("acura")) make = "Acura";
        else if (restLower.includes("hyundai")) make = "Hyundai";
        else make = rest.substring(0, 20); 
    }

    // 6. Format Description (strip HTML)
    const rawDesc = p.description ? p.description.replace(/(<([^>]+)>)/gi, "").trim() : '';
    const desc = rawDesc.replace(/'/g, "''").substring(0, 1500);

    // Default to 'Unknown' if slug is empty somehow
    if (!slug) slug = `vehicle-${Date.now()}-${Math.floor(Math.random()*1000)}`;

    sql += `INSERT INTO public.vehicles (slug, name, description, price, make, year, body_type, images, is_sold, created_at)\n`;
    sql += `VALUES (\n`;
    sql += `  '${slug}',\n`;
    sql += `  '${name}',\n`;
    sql += `  '${desc}',\n`;
    sql += `  ${price},\n`;
    sql += `  '${make}',\n`;
    sql += `  ${year},\n`;
    sql += `  '${category}',\n`;
    sql += `  ${imagesSql},\n`;
    sql += `  false,\n`;
    sql += `  NOW()\n`; // Fallback date if not present in WC store api
    sql += `) ON CONFLICT (slug) DO UPDATE SET \n`;
    sql += `  name = EXCLUDED.name,\n`;
    sql += `  description = EXCLUDED.description,\n`;
    sql += `  price = EXCLUDED.price,\n`;
    sql += `  make = EXCLUDED.make,\n`;
    sql += `  year = EXCLUDED.year,\n`;
    sql += `  body_type = EXCLUDED.body_type,\n`;
    sql += `  images = EXCLUDED.images,\n`;
    sql += `  is_sold = EXCLUDED.is_sold;\n\n`;
  });

  const outputPath = 'supabase/migrations/20260808124000_seed_vehicles.sql';
  fs.writeFileSync(outputPath, sql, 'utf8');
  console.log(`\nSuccess! Perfectly aligned SQL seed file with 40 posts generated at: ${outputPath}`);
}

run();
